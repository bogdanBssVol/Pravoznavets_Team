    def start_music(self, path=None):
        """Спокійна мелодія. Спочатку пробує файл, інакше — згенерований chiptune."""
        if not HAS_SOUND:
            return

        # 1. Якщо є зовнішній файл — граємо його
        try:
            if path and os.path.isfile(path):
                pygame.mixer.music.load(path)
                pygame.mixer.music.set_volume(0.35)
                pygame.mixer.music.play(-1)
                return
        except Exception:
            pass

        # 2. Генеруємо коротку спокійну мелодію в пам’яті
        try:
            import array, math

            sample_rate = 22050
            bpm = 78
            beat = 60.0 / bpm

            # Проста послідовність нот (C major)
            notes = [
                (261.63, 1.0),  # C4
                (293.66, 1.0),  # D4
                (329.63, 1.0),  # E4
                (349.23, 1.0),  # F4
                (392.00, 1.5),  # G4
                (349.23, 0.5),  # F4
                (329.63, 1.0),  # E4
                (293.66, 1.0),  # D4
                (261.63, 2.0),  # C4
                (0,      0.5),  # пауза
                (196.00, 1.0),  # G3
                (220.00, 1.0),  # A3
                (246.94, 1.0),  # B3
                (261.63, 1.5),  # C4
                (246.94, 0.5),  # B3
                (220.00, 1.0),  # A3
                (196.00, 2.0),  # G3
                (0,      1.0),  # пауза
            ]

            buf = array.array("h")

            for freq, beats in notes:
                length = int(sample_rate * beat * beats)
                for i in range(length):
                    t = i / sample_rate
                    # М’яка атака і затухання
                    attack = min(1.0, i / (sample_rate * 0.04))
                    release = min(1.0, (length - i) / (sample_rate * 0.08))
                    env = attack * release

                    if freq < 20:          # пауза
                        sample = 0
                    else:
                        wave = math.sin(2 * math.pi * freq * t)
                        wave += 0.25 * math.sin(2 * math.pi * freq * 2 * t)
                        wave *= (0.85 + 0.15 * math.sin(2 * math.pi * 1.5 * t))
                        sample = int(wave * env * 12000)

                    buf.append(max(-32767, min(32767, sample)))

            sound = pygame.mixer.Sound(buffer=buf)
            sound.set_volume(0.55)

            # Зупиняємо попередній канал, якщо був
            if hasattr(self, "_music_channel") and self._music_channel is not None:
                try:
                    self._music_channel.stop()
                except Exception:
                    pass

            self._music_channel = sound.play(loops=-1)

        except Exception:
            pass

    def stop_music(self):
        if not HAS_SOUND:
            return
        try:
            pygame.mixer.music.fadeout(600)
        except Exception:
            pass
        try:
            if hasattr(self, "_music_channel") and self._music_channel is not None:
                self._music_channel.fadeout(600)
                self._music_channel = None
        except Exception:
            pass

    def quit(self):
        self.stop_music()
        self.stop_tick()
        try:
            self.root.destroy()
        except tk.TclError:
            pass
                     
