def _mute(color, amount=0.45, dark=0.06):
    """Наближає колір до сірого й трохи затемнює (приглушення)."""
    c = color.lstrip("#")
    r, g, b = int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16)
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    out = []
    for v in (r, g, b):
        v = (v * (1 - amount) + lum * amount) * (1 - dark)
        out.append(max(0, min(255, int(round(v)))))
    return "#%02x%02x%02x" % tuple(out)


def _mute_pal(pal):
    res = {}
    for key, col in pal.items():
        if key in ("S", "s"):
            res[key] = _mute(col, 0.15, 0.04)        # шкіра - майже без змін
        elif key == "W":
            res[key] = "#e8e6df"
        else:
            res[key] = _mute(col)
    return res


