    def draw_heart(self, x, y, mode):
        """mode: full - червоне, half - півсерця, empty - порожнє, gold - жовте."""
        p = 2                                   # розмір «пікселя» серця (в одиницях сцени)
        for row, line in enumerate(HEART):
            runs = []                           # склеюємо однакові сусідні пікселі
            for col, ch in enumerate(line):
                if ch == ".":
                    continue
                if ch == "K":
                    color = HEART_OUTLINE
                else:
                    hi = (ch == "W")
                    if mode == "gold":
                        color = HEART_GOLD_HI if hi else HEART_GOLD
                    elif mode == "empty" or (mode == "half" and col > 4):
                        color = HEART_EMPTY
                    else:
                        color = HEART_RED_HI if hi else HEART_RED
                if runs and runs[-1][2] == color and runs[-1][0] + runs[-1][1] == col:
                    runs[-1][1] += 1
                else:
                    runs.append([col, 1, color])
            for col, width, color in runs:
                self.rect(x + col * p, y + row * p, width * p, p, color)

