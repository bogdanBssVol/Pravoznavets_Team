def to_runs(rows):
    """Склеює сусідні однакові пікселі в прямокутники (менше об'єктів = без лагів)."""
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            c = row[x]
            if c == ".":
                x += 1
                continue
            x0 = x
            while x < len(row) and row[x] == c:
                x += 1
            out.append((x0, y, x - x0, c))
    return out


