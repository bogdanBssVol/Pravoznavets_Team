    def _draw_menu_scene(self, w, h):
        """Стримана сцена меню: кабінет, графітова та беж палітра."""
        cv = self.canvas
        cv.delete("all")

        def R(x0, y0, x1, y1, col, tag=""):
            cv.create_rectangle(x0, y0, x1, y1, fill=col, outline="", tags=tag)

        horizon = int(h * 0.66)
        R(0, 0, w, horizon, "#c9bea3")                              # стіна
        R(0, 0, w, max(6, h // 60), "#b4a98d")                      # карниз
        R(0, int(h * 0.50), w, horizon, "#3a4257")                  # панелі
        R(0, int(h * 0.50), w, int(h * 0.50) + 3, "#2a3042")
        pw = max(40, w // 7)
        for x in range(0, w, pw):
            R(x + 6, int(h * 0.53), x + pw - 6, horizon - 8, "#343c50")
        R(0, horizon - 8, w, horizon, "#23262f")                    # плінтус
        R(0, horizon, w, h, "#3d3f47")                              # підлога
        row = max(16, h // 22)
        for i, y in enumerate(range(horizon, h, row)):
            R(0, y, w, y + 1, "#30323a")
            for x in range(0 if i % 2 == 0 else pw // 2, w, pw):
                R(x, y, x + 1, y + row, "#30323a")
        # вікно з жалюзі (праворуч)
        wx0, wy0, wx1, wy1 = int(w * 0.72), int(h * 0.27), int(w * 0.94), int(h * 0.43)
        R(wx0, wy0, wx1, wy1, "#3a3d45")
        R(wx0 + 6, wy0 + 6, wx1 - 6, wy1 - 6, "#a9b3c0")
        for yy in range(wy0 + 6, wy1 - 6 - (wy1 - wy0) // 4, 12):
            R(wx0 + 6, yy, wx1 - 6, yy + 6, "#c9c4b0")
            R(wx0 + 6, yy + 6, wx1 - 6, yy + 8, "#a8a28f")
        # прапор (приглушені кольори)
        pole = max(3, w // 200)
        px0, fy = int(w * 0.06), int(h * 0.25)
        fw = int(w * 0.16)
        stripe = int(fw * 0.34)
        R(px0, fy, px0 + pole, fy + int(h * 0.30), "#4a4034")
        R(px0 + pole, fy + 4, px0 + pole + fw, fy + 4 + stripe, "#35507a")
        R(px0 + pole, fy + 4 + stripe, px0 + pole + fw, fy + 4 + 2 * stripe, "#b79a45")
        # шафа з теками (ліворуч внизу)
        cx0, cy0 = int(w * 0.03), int(h * 0.58)
        R(cx0, cy0, cx0 + int(w * 0.09), horizon, "#7b808b")
        for yy in range(cy0 + 8, horizon - 6, max(14, (horizon - cy0) // 3)):
            R(cx0 + 6, yy, cx0 + int(w * 0.09) - 6, yy + max(10, (horizon - cy0) // 3 - 8),
              "#6a6f79")
        # назва гри
        cx = w // 2
        fs = max(18, int(w * 0.105))
        off = max(2, int(w * 0.006))
        y1 = int(h * 0.09)
        y2 = y1 + int(fs * 1.05)
        for d, col in ((off, "#101114"), (0, "#e4dfd1")):
            cv.create_text(cx + d, y1 + d, text="ЗВИЧАЙНА", fill=col,
                           font=("Courier", -fs, "bold"))
            cv.create_text(cx + d, y2 + d, text="ПОДЯКА", fill=col,
                           font=("Courier", -fs, "bold"))
        cv.create_text(cx, y2 + int(fs * 0.85), text="навчальна гра про доброчесність",
                       fill="#2c3a5a", font=("Courier", -max(12, int(w * 0.04)), "bold"))
        # поліцейський на сірому килимі
        feet = int(h * 0.95)
        ps = max(2, min(int(h * 0.58 / 40), int(w * 0.78 / 24)))
        ox, oy = (w - 24 * ps) // 2, feet - 40 * ps
        cv.create_oval(cx - int(w * 0.36), feet - int(ps * 1.2),
                       cx + int(w * 0.36), feet + int(ps * 1.4),
                       fill="#232c44", outline="#cbbfa3", width=2)
        cv.create_oval(cx - 13 * ps, feet - ps // 2, cx + 13 * ps, feet + ps,
                       fill="#1a2033", outline="")
        for x, y, wd, c in OFFICER_RUNS:
            R(ox + x * ps, oy + y * ps, ox + (x + wd) * ps, oy + (y + 1) * ps,
              OFFICER_PAL[c], "off")
        cv.create_rectangle(2, 2, w - 2, h - 2, outline="#cbbfa3", width=3)
        self._menu_dy = max(2, ps // 6)

