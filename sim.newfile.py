    def story_choose(self, n, i):
        S = STORIES[self.sid]
        o = S["stages"][n]["options"][i]
        r = o["risk"](self.sflags) if callable(o["risk"]) else o["risk"]
        self.svecs.append(tuple(r))
        self.spicks.append(i)
        self.sflags |= set(o.get("flags", []))
        d = dict(o.get("doc", {}))
        add = d.pop("notes_add", 0)
        self.sdoc.update(d)
        self.sdoc["notes"] = min(3, self.sdoc.get("notes", 0) + add)
        if n + 1 < len(S["stages"]):
            self.story_stage(n + 1)
        else:
            self.story_final()

