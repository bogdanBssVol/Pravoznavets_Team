    def _menu_resize(self, w, h):
        cv = self.canvas
        if cv is None or w < 60 or h < 60 or not cv.winfo_exists():
            return
        if self._menu_size == (w, h):
            return
        started = self._menu_size is not None
        self._menu_size = (w, h)
        try:
            self._draw_menu_scene(w, h)
        except Exception:
            return                      # меню лишається робочим навіть без сцени
        if not started:
            self._menu_idle()

    def _draw_menu_scene(self, w, h):
        """Малює сцену під поточний розмір полотна (w x h пікселів)."""
        cv = self.canvas
        cv.delete("all")

        def R(x0, y0, x1, y1, col, tag=""):
            cv.create_rectangle(x0, y0, x1, y1, fill=col, outline="", tags=tag)

        horizon = int(h * 0.66)
        R(0, 0, w, horizon, "#b9d4ee")                           # стіна
        R(0, int(h * 0.52), w, horizon, "#8fb2d6")               # панель
        R(0, horizon, w, h, "#8a6a4a")                           # підлога
        tile = max(20, w // 9)
        for x in range(0, w, tile):
            R(x, horizon, x + 2, h, "#74583c")
        row = horizon + int((h - horizon) * 0.45)
        R(0, row, w, row + 2, "#74583c")

        # прапор України
        pole = max(3, w // 200)
        px0, fy = int(w * 0.06), int(h * 0.25)
        fw = int(w * 0.16)
        stripe = int(fw * 0.34)
        R(px0, fy, px0 + pole, fy + int(h * 0.30), "#5a4a3a")
        R(px0 + pole, fy + 4, px0 + pole + fw, fy + 4 + stripe, "#0057b7")
        R(px0 + pole, fy + 4 + stripe, px0 + pole + fw, fy + 4 + 2 * stripe, "#ffd700")

        # назва гри
        cx = w // 2
        fs = max(18, int(w * 0.11))
        off = max(2, int(w * 0.007))
        y1 = int(h * 0.09)
        y2 = y1 + int(fs * 1.05)
        for d, col in ((off, "#000000"), (0, GOLD)):
            cv.create_text(cx + d, y1 + d, text="ЗВИЧАЙНА", fill=col,
                           font=("Courier", -fs, "bold"))
            cv.create_text(cx + d, y2 + d, text="ПОДЯКА", fill=col,
                           font=("Courier", -fs, "bold"))
        cv.create_text(cx, y2 + int(fs * 0.85), text="навчальна гра про доброчесність",
                       fill="#1f3a8a", font=("Courier", -max(12, int(w * 0.04)), "bold"))

        # поліцейський (великий) на килимі
        feet = int(h * 0.95)
        ps = max(2, min(int(h * 0.58 / 40), int(w * 0.78 / 24)))
        ox, oy = (w - 24 * ps) // 2, feet - 40 * ps
        cv.create_oval(cx - int(w * 0.36), feet - int(ps * 1.2),
                       cx + int(w * 0.36), feet + int(ps * 1.4),
                       fill="#34508f", outline="#1f3a8a", width=2)
        cv.create_oval(cx - 13 * ps, feet - ps // 2, cx + 13 * ps, feet + ps,
                       fill="#26407a", outline="")
        for x, y, wd, c in OFFICER_RUNS:
            R(ox + x * ps, oy + y * ps, ox + (x + wd) * ps, oy + (y + 1) * ps,
              OFFICER_PAL[c], "off")

        cv.create_rectangle(2, 2, w - 2, h - 2, outline=GOLD, width=3)   # рамка
        self._menu_dy = max(2, ps // 6)

    def _menu_idle(self):
        """Легке «дихання» поліцейського в меню."""
        state = {"up": False}

        def tick():
            cv = self.canvas
            if cv is None or not cv.winfo_exists():
                self.tick_id = None
                return
            dy = getattr(self, "_menu_dy", 2)
            cv.move("off", 0, dy if state["up"] else -dy)
            state["up"] = not state["up"]
            self.tick_id = self.root.after(550, tick)

        self.tick_id = self.root.after(550, tick)

