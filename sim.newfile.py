def _make_tone(freq=880, duration=0.045, volume=0.18, wave="square"):
    """Короткий тон у пам’яті (без файлів)."""
    if not HAS_SOUND:
        return None
    import array, math
    sample_rate = 22050
    n = int(sample_rate * duration)
    buf = array.array("h")
    amp = int(32767 * volume)
    for i in range(n):
        t = i / sample_rate
        # легке згасання, щоб не клацало різко
        env = 1.0 - (i / n) * 0.7
        if wave == "square":
            val = amp if (int(t * freq) % 2 == 0) else -amp
        else:  # soft sine
            val = int(amp * math.sin(2 * math.pi * freq * t))
        buf.append(int(val * env))
    sound = pygame.mixer.Sound(buffer=buf)
    return sound

