    def start_quiz(self):
        self.play_soft()
        self.q_idx = 0
        self.q_score = 0
        self.q_log = []
        self.render_quiz_question()

    def render_quiz_question(self):
        if self.q_idx >= len(TERMS_QUIZ):
            self.finish_quiz()
            return
        item = TERMS_QUIZ[self.q_idx]
        indexed = list(enumerate(item["opts"]))
        random.shuffle(indexed)

        self.reset()
        letters = ("А", "Б", "В", "Г")
        for pos, (orig_idx, text) in enumerate(indexed):
            is_correct = (orig_idx == item["ans"])
            self.button(
                "%s. %s" % (letters[pos], text),
                lambda ok=is_correct, chosen=text: self.answer_quiz(ok, chosen)
            )
        self.button("< Перервати та повернутися в меню", self.show_menu)

        meter = int((self.q_score / max(1, self.q_idx)) * 100) if self.q_idx > 0 else 100
        self.scene(self.q_idx + 1, meter, "Оберіть правильне визначення.", "off")
        self.textbox(
            "Запитання %d із %d" % (self.q_idx + 1, len(TERMS_QUIZ)),
            item["q"]
        )

    def answer_quiz(self, is_correct, chosen_text):
        item = TERMS_QUIZ[self.q_idx]
        if is_correct:
            self.q_score += 1
            self.play_ok()
        else:
            self.play_err()
        right_text = item["opts"][item["ans"]]
        self.q_log.append((
            self.q_idx + 1, is_correct, item["q"],
            chosen_text, right_text, item["exp"]
        ))
        self.q_idx += 1
        self.render_quiz_question()

    def finish_quiz(self):
        total = len(TERMS_QUIZ)
        score = self.q_score
        meter = int(score * 100 / total)

        if score >= 9:
            verdict = "Відмінний результат! Ви впевнено володієте основними термінами."
            bubble = "Відмінний результат!"
        elif score >= 6:
            verdict = "Добрий результат. Окремі визначення варто переглянути ще раз."
            bubble = "Добре, але є над чим попрацювати."
        else:
            verdict = "Варто уважно перечитати розбір нижче та пройти тест повторно."
            bubble = "Повторіть основні терміни!"

        lines = [
            "Результат: %d з %d правильних відповідей (%d%%)." % (score, total, meter),
            verdict, "",
            "────────── Детальний розбір ──────────",
        ]
        for num, ok, q, chosen, right, exp in self.q_log:
            status = "[+] ПРАВИЛЬНО" if ok else "[-] ПОМИЛКА"
            lines.append("\n%d. %s" % (num, status))
            lines.append("Питання: %s" % q)
            if not ok:
                lines.append("Ваша відповідь: %s" % chosen)
            lines.append("Правильна відповідь: %s" % right)
            lines.append("Пояснення: %s" % exp)

